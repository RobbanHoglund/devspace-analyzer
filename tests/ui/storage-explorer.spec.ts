import { test, expect } from '@playwright/test';
import { loadReport, navigate, storageMapReport } from './fixtures';

for (const width of [380, 1440]) test(`nested tiles link to their folders, shared list and history at ${width}px`, async ({ page }) => {
  await page.setViewportSize({ width, height: 1000 });
  await loadReport(page, storageMapReport()); await navigate(page, 'Storage');
  const map = page.getByRole('region', { name: 'Interactive folder map' });
  await map.getByRole('button', { name: /^Open folder: Workspace,/ }).click();
  const preview = map.getByRole('group', { name: 'Inside build' });
  const classes = preview.getByRole('button', { name: /^Open subfolder: classes,/ });
  await expect(classes).toHaveAttribute('data-value', String(40 * 1024 ** 2));
  const buildRow = map.locator('[data-map-id="folder-1"]');
  await classes.hover(); await expect(buildRow).toHaveClass(/storage-row-active/);
  await expect(map.locator('.map-caption')).toContainText('build / classes');
  await page.mouse.move(0, 0);
  const nodeRow = map.locator('[data-map-id="folder-2"]');
  await nodeRow.locator('.storage-entry').focus();
  await expect(map.getByRole('button', { name: /^Open folder: node_modules,/ })).toHaveClass(/map-active/);
  await expect(buildRow).not.toHaveClass(/storage-row-active/);
  await classes.focus(); await page.keyboard.press('Enter');
  const crumbs = page.getByRole('navigation', { name: 'Storage path' });
  await expect(crumbs.locator('[aria-current]')).toHaveText('classes');
  await page.getByRole('button', { name: 'Go back', exact: true }).click();
  await expect(crumbs.locator('[aria-current]')).toHaveText('Workspace');
  await expect(classes).toBeFocused();
  await page.getByRole('button', { name: 'Go forward', exact: true }).click();
  await page.getByRole('button', { name: 'Up one level', exact: true }).click();
  await expect(crumbs.locator('[aria-current]')).toHaveText('build');
  await page.getByRole('button', { name: 'Up one level', exact: true }).click();
  const chart = (await map.locator('.treemap-surface').boundingBox())!;
  const list = (await map.getByRole('region', { name: 'Map details' }).boundingBox())!;
  if (width > 1050) expect(list.x).toBeGreaterThan(chart.x + chart.width);
  else expect(list.y).toBeGreaterThan(chart.y + chart.height);
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(width + 1);
  await expect(page.locator('button button')).toHaveCount(0);
  await page.mouse.move(0, 0);
  await page.screenshot({ path: `test-results/storage-explorer-${width}.png` });
});

test('a group opened inside a parent preview gets the right folder breadcrumb and contents', async ({ page }) => {
  await loadReport(page, storageMapReport()); await navigate(page, 'Storage');
  const preview = page.getByRole('group', { name: 'Inside Workspace' });
  await preview.getByRole('button', { name: /^Explore contents: Files directly here,/ }).focus();
  await page.keyboard.press('Enter');
  const crumbs = page.getByRole('navigation', { name: 'Storage path' });
  await expect(crumbs).toContainText('Workspace');
  await expect(crumbs.locator('[aria-current]')).toHaveText('Files directly here');
  const details = page.getByRole('region', { name: 'Map details' });
  await expect(details).toContainText('README.md');
  await expect(details).toContainText('Other direct files');
  await expect(details).not.toContainText('node_modules');
  await page.getByRole('button', { name: 'Up one level', exact: true }).click();
  await expect(crumbs.locator('[aria-current]')).toHaveText('Workspace');
});

test('small folders remain reachable through the list and grouped map, including later pages', async ({ page }) => {
  const report = storageMapReport(), root = report.storage!.directories[0];
  report.findings = []; report.projects = [];
  root.directFileBytes = 0; root.largestFiles = []; root.logicalBytes = 30 * 1024;
  report.progress.logicalBytes = root.logicalBytes;
  report.storage!.directories = [root, ...Array.from({ length: 30 }, (_, i) => ({ ...root, id: i + 1, parentId: 0, path: `${root.path}/small-${String(i).padStart(2, '0')}`, logicalBytes: 1024, directFileBytes: 1024, classifiedBytes: 0, directClassifiedBytes: 0 }))];
  await loadReport(page, report); await navigate(page, 'Storage');
  const map = page.getByRole('region', { name: 'Interactive folder map' });
  await map.getByRole('button', { name: /^Open folder: Workspace,/ }).click();
  const details = page.getByRole('region', { name: 'Map details' });
  await details.getByRole('button', { name: 'Next', exact: true }).click();
  const last = details.locator('.storage-folder').last();
  const name = await last.locator('.storage-entry-name').evaluate(el => el.firstChild!.textContent!);
  await last.focus();
  await expect(map.locator('.map-tile.map-active')).toHaveCount(1);
  await page.keyboard.press('Enter');
  await expect(page.getByRole('navigation', { name: 'Storage path' }).locator('[aria-current]')).toHaveText(name);
  await page.getByRole('button', { name: 'Go back', exact: true }).click();
  await expect(details.locator('.pagination')).toContainText('11–20 of 30 items');
  await expect(details.locator('.storage-folder').last()).toBeFocused();
  await map.getByRole('button', { name: /^Explore group:/ }).click();
  await expect(details).not.toContainText('30 items');
  await expect(details.locator('.storage-folder').first()).toBeVisible();
});
